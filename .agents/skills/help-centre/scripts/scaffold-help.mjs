#!/usr/bin/env node
/**
 * Scaffold a role-scoped help centre from `help.config.mjs`.
 *
 * Writes, into the target project:
 *   <srcDir>/lib/help.ts                 guide data (one source of truth)
 *   <srcDir>/components/HelpGuide.tsx    guide card + table of contents
 *   <srcDir>/components/RoleHelpPage.tsx shared role page
 *   <srcDir>/app/help/<role>/page.tsx    one page per role
 *   <srcDir>/app/help/page.tsx           hub listing the roles (only if absent)
 *
 * Existing files are left untouched unless --force is passed, so the script is
 * safe to re-run after editing the config.
 *
 * Usage (from the target project root):
 *
 *   node .agents/skills/help-centre/scripts/scaffold-help.mjs
 *   node .../scaffold-help.mjs --force
 *
 * Config keys used: roles, outDir. Set SRC_DIR to override the default src root
 * (apps/web/src).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const CONFIG_PATH = resolve(process.env.HELP_CONFIG || 'help.config.mjs');
const SRC = resolve(process.env.SRC_DIR || 'apps/web/src');
const FORCE = process.argv.includes('--force');

const mod = await import(pathToFileURL(CONFIG_PATH).href).catch(() => {
  console.error(`Could not load help config at ${CONFIG_PATH}`);
  process.exit(1);
});
const cfg = mod.default;
const roles = Object.keys(cfg.roles || {});
if (roles.length === 0) {
  console.error('help.config.mjs has no roles configured.');
  process.exit(1);
}

/** Screenshot basename for a guide, matching capture-screenshots.mjs. */
const shotName = (role, id) => `${role}-${id}.png`;

function write(path, contents) {
  if (existsSync(path) && !FORCE) {
    console.log(`  skip (exists): ${path}`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
  console.log(`  wrote: ${path}`);
}

// --- lib/help.ts ----------------------------------------------------------
const guideArray = (role) =>
  (cfg.roles[role] || [])
    .map(
      (g) => `  {
    id: ${JSON.stringify(g.id)},
    icon: ${JSON.stringify(g.icon)},
    title: ${JSON.stringify(g.title)},
    summary: ${JSON.stringify(g.summary)},
    route: ${JSON.stringify(g.route)},
    screenshot: ${JSON.stringify(shotName(role, g.id))},
    steps: [
${(g.steps || []).map((s) => `      ${JSON.stringify(s)},`).join('\n')}
    ],
  },`,
    )
    .join('\n');

const constName = (role) => `${role.toUpperCase()}_GUIDES`;
const switchCases = roles
  .slice(1)
  .map((r) => `    case '${r}':\n      return ${constName(r)};`)
  .join('\n');
const helpTs = `/**
 * Help-centre content. Generated by the help-centre skill; edit help.config.mjs
 * and re-run scaffold-help.mjs, or edit here directly.
 *
 * Each guide walks through one shipped surface with numbered steps and a real
 * screenshot of the running app (/public/help/<screenshot>). Content is data,
 * not JSX, so the hub, the role pages, and the tests read one source.
 */

export type HelpRole = ${roles.map((r) => `'${r}'`).join(' | ')};

export interface HelpGuide {
  /** Stable key, also the anchor id and the screenshot filename suffix. */
  id: string;
  icon: string;
  title: string;
  summary: string;
  /** Live surface the guide documents. */
  route: string;
  /** Screenshot filename under the help image directory. */
  screenshot: string;
  steps: string[];
}

${roles
  .map((role) => `export const ${constName(role)}: HelpGuide[] = [\n${guideArray(role)}\n];`)
  .join('\n\n')}

/** The guides for a role, defaulting to "${roles[0]}" for unknown roles. */
export function guidesFor(role: HelpRole | string | undefined): HelpGuide[] {
  switch (role) {
${switchCases}
    default:
      return ${constName(roles[0])};
  }
}

/** Look up a guide by id within a role's set. */
export function guideById(
  role: HelpRole,
  id: string,
): HelpGuide | undefined {
  return guidesFor(role).find((g) => g.id === id);
}
`;

// --- components/HelpGuide.tsx --------------------------------------------
const helpGuideTsx = `import Link from 'next/link';
import type { HelpGuide as Guide } from '@/lib/help';

/** One help guide: header, screenshot of the running surface, numbered steps. */
export function HelpGuideCard({ guide }: { guide: Guide }) {
  return (
    <section id={guide.id} className="card help-guide">
      <div className="row">
        <h2 style={{ margin: 0 }}>
          <span aria-hidden style={{ marginRight: 8 }}>{guide.icon}</span>
          {guide.title}
        </h2>
        <Link className="btn secondary" href={guide.route}>
          Open {guide.title} →
        </Link>
      </div>
      <p className="muted" style={{ maxWidth: 640 }}>{guide.summary}</p>
      <img
        className="help-shot"
        src={\`/help/\${guide.screenshot}\`}
        alt={\`\${guide.title} screenshot\`}
        loading="lazy"
      />
      <ol className="help-steps">
        {guide.steps.map((step) => (
          <li key={step}>{step}</li>
        ))}
      </ol>
    </section>
  );
}

/** Sticky table of contents so a reader can jump to a feature. */
export function HelpToc({ guides }: { guides: Guide[] }) {
  return (
    <nav className="card help-toc" aria-label="Guides on this page">
      <h3 style={{ marginTop: 0 }}>On this page</h3>
      <ul>
        {guides.map((g) => (
          <li key={g.id}>
            <a href={\`#\${g.id}\`}>{g.title}</a>
          </li>
        ))}
      </ul>
    </nav>
  );
}
`;

// --- components/RoleHelpPage.tsx -----------------------------------------
const roleHelpPageTsx = `import Link from 'next/link';
import { HelpGuideCard, HelpToc } from '@/components/HelpGuide';
import { guidesFor, type HelpRole } from '@/lib/help';

/** A role's help page: every shipped feature as a walkthrough with a shot. */
export function RoleHelpPage({ role }: { role: HelpRole }) {
  const guides = guidesFor(role);
  const others = ([${roles.map((r) => `'${r}'`).join(', ')}] as HelpRole[]).filter(
    (r) => r !== role,
  );

  return (
    <div>
      <div className="row">
        <h1 style={{ marginBottom: 0 }}>
          {role[0].toUpperCase() + role.slice(1)} guides
        </h1>
        {others.map((o) => (
          <Link key={o} className="btn secondary" href={\`/help/\${o}\`}>
            {o[0].toUpperCase() + o.slice(1)} guides →
          </Link>
        ))}
      </div>
      <p className="muted" style={{ maxWidth: 680 }}>
        Step-by-step walkthroughs for every {role} feature, each with a
        screenshot of the live screen. Open a guide&rsquo;s feature, follow the
        numbered steps, and you are done.
      </p>

      <div className="help-layout">
        <HelpToc guides={guides} />
        <div className="help-guides">
          {guides.map((guide) => (
            <HelpGuideCard key={guide.id} guide={guide} />
          ))}
        </div>
      </div>

      <p className="muted" style={{ marginTop: 16 }}>
        <Link href="/help">← All help</Link>
      </p>
    </div>
  );
}
`;

// --- app/help/<role>/page.tsx --------------------------------------------
const rolePage = (role) => {
  const title = role[0].toUpperCase() + role.slice(1);
  return `import type { Metadata } from 'next';
import { RoleHelpPage } from '@/components/RoleHelpPage';

export const metadata: Metadata = {
  title: '${title} guides — Help',
  description: 'Step-by-step guides with screenshots for every ${role} feature.',
};

export default function ${title}HelpPage() {
  return <RoleHelpPage role="${role}" />;
}
`;
};

// --- app/help/page.tsx (hub, only if absent) ------------------------------
const hubPage = `import Link from 'next/link';

/** Help hub: pick a role to reach its guides. */
export default function HelpPage() {
  return (
    <div>
      <h1>Help</h1>
      <p className="muted" style={{ maxWidth: 640 }}>
        Step-by-step guides with screenshots for every feature. Pick your role.
      </p>
      <div className="grid" style={{ marginTop: 16 }}>
${roles
  .map((role) => {
    const title = role[0].toUpperCase() + role.slice(1);
    const n = (cfg.roles[role] || []).length;
    return `        <Link className="card" href="/help/${role}">
          <h3 style={{ marginTop: 0 }}>${title} guides</h3>
          <p className="muted" style={{ marginBottom: 0 }}>
            ${n} guide${n === 1 ? '' : 's'} for the ${role} experience.
          </p>
        </Link>`;
  })
  .join('\n')}
      </div>
      <p className="muted" style={{ marginTop: 16 }}>
        <Link href="/dashboard">← Back to dashboard</Link>
      </p>
    </div>
  );
}
`;

console.log(`Scaffolding help centre (roles: ${roles.join(', ')})`);
write(join(SRC, 'lib/help.ts'), helpTs);
write(join(SRC, 'components/HelpGuide.tsx'), helpGuideTsx);
write(join(SRC, 'components/RoleHelpPage.tsx'), roleHelpPageTsx);
for (const role of roles) {
  write(join(SRC, 'app/help', role, 'page.tsx'), rolePage(role));
}
write(join(SRC, 'app/help/page.tsx'), hubPage);

// Read the config back so callers can confirm the guide list.
const total = roles.reduce((n, r) => n + (cfg.roles[r] || []).length, 0);
console.log(`\nDone. ${total} guides across ${roles.length} roles.`);
console.log('Next: run capture-screenshots.mjs, then verify-help.mjs.');
